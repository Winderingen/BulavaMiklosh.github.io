function getDepartmentKeys() {
    return Object.keys(RANKS_DB);
}

function getDepartmentName(depKey) {
    return RANKS_DB[depKey]?.displayName || depKey;
}

function getDepartmentShortName(depKey) {
    return RANKS_DB[depKey]?.name || depKey;
}

function getAllRanks(depKey) {
    const dep = RANKS_DB[depKey];
    if (!dep) return [];
    const set = new Set();
    dep.paths.forEach(p => {
        set.add(p.from);
        set.add(p.to);
    });
    return Array.from(set);
}

function getCurrentPath(depKey, from, to) {
    const dep = RANKS_DB[depKey];
    if (!dep) return null;
    return dep.paths.find(p => p.from === from && p.to === to) || null;
}

function getNextRank(depKey, currentRank) {
    const dep = RANKS_DB[depKey];
    if (!dep) return null;
    
    // Находим путь, где from === currentRank
    const path = dep.paths.find(p => p.from === currentRank);
    if (path) {
        return path.to;
    }
    return null;
}

